function soft(s) {
  return (s || "").replace(/\s+/g, " ").trim().toLowerCase();
}
function hasDup(opts) {
  const t = (opts || []).map((o) => soft(o.text));
  return t.some((x, i) => x && t.indexOf(x) !== i);
}

function fixIzohLegal(s) {
  if (!s) return s;
  let out = s;
  out = out.replace(/МПК/g, "ПДД");
  out = out.replace(/Уголовного кодекса/gi, "ПДД");
  out = out.replace(/Уголовном кодексе/gi, "ПДД");
  out = out.replace(/статьи\s+(\d+)\s+главы\s+(\d+)\s+Уголовного/gi, "пункту $1 главы $2 ПДД");
  out = out.replace(/\s+о гражданском процессе/gi, "");
  out = out.replace(/\s+по гражданскому процессу/gi, "");
  out = out.replace(/Глава\s+(\d+)\s+ООН/gi, "Глава $1 ПДД");
  out = out.replace(/главы\s+(\d+)\s+ООН/gi, "главы $1 ПДД");
  out = out.replace(/запрещается сбор в следующих местах/gi, "запрещается разворот в следующих местах");
  out = out.replace(/YHQ,\s*1\.16\.\s*Знак/g, "Приложение 1 ПДД, знак 1.16");
  out = out.replace(/Общие правила YHQ:/g, "Общие положения ПДД:");
  return out;
}

